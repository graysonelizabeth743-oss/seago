// Generates src/features/map/mapData.js from Natural Earth (via world-atlas).
// Run: npm run build:map   (only needed if you change the extent or projection)
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature, mesh } from "topojson-client";
import { geoNaturalEarth1, geoPath, geoGraticule } from "d3-geo";

const require = createRequire(import.meta.url);
const world = require("world-atlas/countries-110m.json");

const W = 1000;
const CENTER = 2; // central meridian (degrees east)
const EXTENT = [[-128, -58], [133, 72]]; // lon/lat box the map is fitted to

const countries = feature(world, world.objects.countries);
const borders = mesh(world, world.objects.countries, (a, b) => a !== b);

const outline = geoGraticule().extent(EXTENT).outline();
const proj = geoNaturalEarth1().rotate([-CENTER, 0]);

// Work out the height that matches the box's natural aspect ratio
const probe = geoPath(proj.scale(1).translate([0, 0])).bounds(outline);
const aspect = (probe[1][1] - probe[0][1]) / (probe[1][0] - probe[0][0]);
const H = Math.round(W * aspect);
proj.fitSize([W, H], outline).clipExtent([[-30, -30], [W + 30, H + 30]]);

const path = geoPath(proj).digits(1);
const land = path(countries);
const border = path(borders);

const out = `// AUTO-GENERATED by scripts/build-map.mjs. Do not edit by hand.
// Natural Earth 1:110m via world-atlas. Projection: Natural Earth I, central meridian ${CENTER}°E.
export const MAP = {
  width: ${W},
  height: ${H},
  center: ${CENTER},
  k: ${proj.scale()},
  tx: ${proj.translate()[0]},
  ty: ${proj.translate()[1]},
  extent: ${JSON.stringify(EXTENT)},
  land: ${JSON.stringify(land)},
  borders: ${JSON.stringify(border)},
};
`;
fs.writeFileSync(new URL("../src/features/map/mapData.js", import.meta.url), out);
console.log(`map ${W}x${H}  k=${proj.scale().toFixed(2)}  land=${(land.length/1024).toFixed(0)}KB borders=${(border.length/1024).toFixed(0)}KB`);
